use std::{collections::BTreeMap, fmt::Write};

use anyhow::Result;

use super::{lunar_math, Entry};

const FIRST_JD: f64 = 2_458_849.5;
const END_JD: f64 = 2_470_172.5;
const END_T: f64 = (END_JD - 2_451_545.0) / 36_525.0;
const BUDGET: [f64; 3] = [12.0, 8.0, 10.0]; // arcsec, arcsec, km

enum Argument {
    Main([i8; 4]),
    Linear { phase: f64, rate: f64, power: usize },
}

struct Term {
    amplitude: f64,
    argument: Argument,
}

impl Term {
    fn from_entry(axis: usize, series: usize, entry: &Entry) -> Result<Self> {
        let mut floats = entry.floats.iter().map(|s| s.parse::<f64>());
        let first = floats.next().unwrap()?;
        if series <= 3 {
            let mut multipliers = [0; 4];
            for (target, &source) in multipliers.iter_mut().zip(&entry.ints) {
                *target = i8::try_from(source)?;
            }
            let derivatives = floats.collect::<std::result::Result<Vec<_>, _>>()?;
            let amplitude =
                lunar_math::main_amplitude(axis, first, derivatives.try_into().unwrap());
            return Ok(Self {
                amplitude,
                argument: Argument::Main(multipliers),
            });
        }

        let mut phase = first.to_radians();
        let mut rate = 0.0;
        for (&multiplier, &[offset, slope]) in entry
            .ints
            .iter()
            .zip(lunar_math::perturbation_basis(series))
        {
            phase += multiplier as f64 * offset;
            rate += multiplier as f64 * slope;
        }
        Ok(Self {
            amplitude: floats.next().unwrap()?,
            argument: Argument::Linear {
                phase: phase % std::f64::consts::TAU,
                rate,
                power: lunar_math::time_power(series),
            },
        })
    }

    fn bound(&self) -> f64 {
        let power = match self.argument {
            Argument::Main(_) => 0,
            Argument::Linear { power, .. } => power,
        };
        self.amplitude.abs() * [1.0, END_T, END_T * END_T][power]
    }
}

pub(super) fn generate(data: &BTreeMap<String, Vec<Entry>>, sha: &str) -> Result<String> {
    let mut output = format!(
        "// Generated by src/elp/compact_codegen.rs from IMCCE ELP2000-82B.\n\
         // Raw source: https://ftp.imcce.fr/pub/ephem/moon/elp82b/\n\
         /// SHA-256 of the raw ELP files (sorted names, NUL, then file contents).\n\
         pub const SOURCE_SHA256: &str = \"{sha}\";\n\
         /// First supported TDB Julian date, 2020-01-01 inclusive.\n\
         pub const FIRST_JD_TDB: f64 = {FIRST_JD:.1};\n\
         /// Exclusive upper bound, 2051-01-01 TDB.\n\
         pub const END_JD_TDB: f64 = {END_JD:.1};\n"
    );
    for (axis, (name, budget)) in ["LONGITUDE", "LATITUDE", "DISTANCE"]
        .into_iter()
        .zip(BUDGET)
        .enumerate()
    {
        let mut terms = Vec::new();
        for series in (axis + 1..=36).step_by(3) {
            for entry in &data[&format!("ELP{series}")] {
                terms.push(Term::from_entry(axis, series, entry)?);
            }
        }

        let mut ranking: Vec<_> = terms
            .iter()
            .enumerate()
            .map(|(i, term)| (term.bound(), i))
            .collect();
        ranking.sort_unstable_by(|a, b| a.0.total_cmp(&b.0).then(a.1.cmp(&b.1)));
        let mut discarded = 0.0;
        let mut keep = vec![true; terms.len()];
        for (bound, index) in ranking {
            if discarded + bound > budget {
                break;
            }
            discarded += bound;
            keep[index] = false;
        }

        writeln!(
            output,
            "// {name} omitted envelope {discarded} (budget {budget})"
        )?;
        writeln!(output, "pub(super) static {name}_MAIN: &[MainTerm] = &[")?;
        let mut linear = [String::new(), String::new(), String::new()];
        for (term, keep) in terms.into_iter().zip(keep) {
            if !keep {
                continue;
            }
            let a = term.amplitude;
            match term.argument {
                Argument::Main(m) => writeln!(output, "    MainTerm {{ a: {a:?}, m: {m:?} }},")?,
                Argument::Linear { phase, rate, power } => {
                    writeln!(linear[power], "        [{a:?}, {phase:?}, {rate:?}],")?;
                }
            }
        }
        writeln!(output, "];")?;
        writeln!(
            output,
            "pub(super) static {name}_PERT: [&[[f64; 3]]; 3] = ["
        )?;
        for terms in linear {
            writeln!(output, "    &[\n{terms}    ],")?;
        }
        writeln!(output, "];")?;
    }
    Ok(output)
}
